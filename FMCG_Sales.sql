-- Q32.Using two CTEs — order counts and total quantity purchased per customer 
-- find customers with more than 2 orders AND more than 100 units purchased.
WITH customer_orders AS (
  SELECT customer_id, COUNT(*) AS total_orders
  FROM orders GROUP BY customer_id
),
customer_quantity AS (
  SELECT o.customer_id, SUM(oi.quantity) AS total_units
  FROM orders o JOIN order_items oi ON o.order_id = oi.order_id
  GROUP BY o.customer_id
)
SELECT c.customer_name, co.total_orders, cq.total_units
FROM customer_orders co
JOIN customer_quantity cq ON co.customer_id = cq.customer_id
JOIN customers c ON c.customer_id = co.customer_id
WHERE co.total_orders > 2 AND cq.total_units > 100; 

-- Q33.Three month moving average with month year and total sales. 
 with monthly_sales as (
    select 
       DATE_FORMAT(o.order_date, '%m-%y') as month_year,
       DATE_FORMAT(o.order_date, '%Y-%m') as sort_month,
       SUM(oi.quantity * oi.unit_price) as total_sales
       from orders o 
       join order_items oi 
          on o.order_id = oi.order_id 
	   group by 
       DATE_FORMAT(o.order_date, '%m-%y') ,
       DATE_FORMAT(o.order_date, '%Y-%m') 
	) 
select  
      month_year,
      total_sales,
      round(AVG(total_sales ) over(
          order by sort_month 
          rows between 2 preceding and current row 
          ), 2 ) as moving_3_month_avg 
from monthly_sales 
order by sort_month;

