-- Q26.Create FMCG sales report with the help of view and show all data in one table.
CREATE VIEW fmcg_sales_report AS
SELECT 
	o.order_id , o.order_date , o.status,
	c.customer_id , c.customer_name , c.store_type,
    r.region_id,
	r.region_name,
    e.employee_id,
	CONCAT(e.first_name,' ',e.last_name) AS employee_name,
    e.designation AS employee_designation,
	CONCAT(m.first_name,' ',m.last_name) AS manager_name,
    p.product_id , p.product_name,
    cat.category_id, cat.category_name,
    s.supplier_id, s.supplier_name,
    oi.quantity , oi.unit_price,
    oi.quantity * oi.unit_price AS sales_amount,
    oi.quantity * p.unit_cost AS cost_amount,
    oi.quantity * (oi.unit_price-p.unit_cost) AS profit
FROM orders o
JOIN customers c
	ON o.customer_id = c.customer_id
JOIN regions r
	ON c.region_id = r.region_id
JOIN employees e
	ON o.employee_id = e.employee_id
LEFT JOIN employees m 
	ON e.manager_id = m.employee_id
JOIN order_items oi
	ON o.order_id = oi.order_id
JOIN products p
	ON oi.product_id = p.product_id
JOIN categories cat
	ON p.category_id = cat.category_id
JOIN suppliers s
	ON p.supplier_id = s.supplier_id;
SELECT * from fmcg_sales_report;

